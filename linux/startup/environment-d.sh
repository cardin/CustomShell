#!/usr/bin/env bash

# Publishes CustomShell's selected environment variables atomically so supported
# GUI and user services never observe a partially generated configuration. A
# second, shell-quoted artifact is published for POSIX login profiles
# (~/.profile and `sh -lc` / `bash -lc`), which do not read ~/.bashrc.

customshell_env_dir="${HOME:?HOME is not set}/.config/environment.d"
customshell_env_file="$customshell_env_dir/90-customshell.conf"
customshell_shell_dir="${HOME:?HOME is not set}/.config/customshell"
customshell_shell_file="$customshell_shell_dir/env.sh"

# GTK_OVERLAY_SCROLLING and UV_SYSTEM_CERTS are fixed values supplied by the
# installer-managed profile block. The certificate variables are different:
# CUSTOM_CA_CERT may be added, changed, or removed after installation, and its
# file must still exist. certificates.sh validates it on every startup and only
# then exports these paths, which this file publishes for graphical applications,
# user services, and POSIX login shells.
customshell_file_envs=("REQUESTS_CA_BUNDLE" "NODE_EXTRA_CA_CERTS")
customshell_value_envs=("GTK_OVERLAY_SCROLLING" "UV_SYSTEM_CERTS")
customshell_env_pairs=()

# customshell_shell_quote
# Quotes a value for a single-quoted POSIX shell literal.
customshell_shell_quote() {
	local customshell_quote_value=$1
	customshell_quote_value=${customshell_quote_value//\'/\'\\\'\'}
	printf "'%s'" "$customshell_quote_value"
}

# customshell_render_shell_exports
# Prints a shell-quoted export list for NAME=value pairs. The output is safe to
# source from POSIX sh, including values with spaces and shell metacharacters.
customshell_render_shell_exports() {
	printf '%s\n' '# Generated by CustomShell; do not edit.'
	local customshell_export_pair customshell_export_name customshell_export_value
	for customshell_export_pair in "$@"; do
		customshell_export_name=${customshell_export_pair%%=*}
		customshell_export_value=${customshell_export_pair#*=}
		printf 'export %s=%s\n' "$customshell_export_name" \
			"$(customshell_shell_quote "$customshell_export_value")"
	done
}

# customshell_publish_lines
# Atomically replaces target with lines. An unchanged target keeps its inode.
customshell_publish_lines() {
	local customshell_publish_target=$1
	shift
	local customshell_publish_dir customshell_publish_tmp customshell_publish_line
	customshell_publish_dir=$(dirname -- "$customshell_publish_target")
	mkdir -p -- "$customshell_publish_dir" || return 1
	customshell_publish_tmp=$(mktemp "$customshell_publish_dir/.$(basename -- "$customshell_publish_target").XXXXXX") || return 1
	chmod 600 "$customshell_publish_tmp"

	for customshell_publish_line in "$@"; do
		printf '%s\n' "$customshell_publish_line" >>"$customshell_publish_tmp" || {
			rm -f -- "$customshell_publish_tmp"
			return 1
		}
	done

	if [[ -f "$customshell_publish_target" ]] && cmp -s -- "$customshell_publish_tmp" "$customshell_publish_target"; then
		rm -f -- "$customshell_publish_tmp"
		return 0
	fi

	if mv -f -- "$customshell_publish_tmp" "$customshell_publish_target"; then
		return 0
	fi
	rm -f -- "$customshell_publish_tmp"
	return 1
}

for customshell_env_name in "${customshell_file_envs[@]}"; do
	if [[ -n "${!customshell_env_name+x}" && -f "${!customshell_env_name}" ]]; then
		customshell_env_value="${!customshell_env_name}"
		if [[ "$customshell_env_value" != *$'\n'* && "$customshell_env_value" != *'$'* ]]; then
			customshell_env_pairs+=("$customshell_env_name=$customshell_env_value")
		fi
	fi
done
for customshell_env_name in "${customshell_value_envs[@]}"; do
	if [[ -n "${!customshell_env_name+x}" ]]; then
		customshell_env_value="${!customshell_env_name}"
		if [[ "$customshell_env_value" != *$'\n'* && "$customshell_env_value" != *'$'* ]]; then
			customshell_env_pairs+=("$customshell_env_name=$customshell_env_value")
		fi
	fi
done

customshell_publish_lines "$customshell_env_file" "${customshell_env_pairs[@]}" || true

customshell_shell_lines=()
while IFS= read -r customshell_shell_line; do
	customshell_shell_lines+=("$customshell_shell_line")
done < <(customshell_render_shell_exports "${customshell_env_pairs[@]}")
customshell_publish_lines "$customshell_shell_file" "${customshell_shell_lines[@]}" || true

unset customshell_env_dir customshell_env_file customshell_shell_dir customshell_shell_file
unset customshell_file_envs customshell_value_envs customshell_env_pairs
unset customshell_env_name customshell_env_value
unset customshell_shell_lines customshell_shell_line
