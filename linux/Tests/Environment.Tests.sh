#!/usr/bin/env bash
# shellcheck disable=SC1090,SC2016,SC2329

# Exercises atomic and idempotent environment publication without touching the
# user's real configuration directory. Covers both the systemd environment.d
# file and the shell-quoted artifact used by POSIX login profiles.

set -u

test_root="$(mktemp -d)" || exit 1
trap 'rm -rf -- "$test_root"' EXIT

# fail
# Reports an assertion failure and terminates the environment test script.
fail() {
	echo "FAIL: $*" >&2
	exit 1
}

export HOME="$test_root/home"
export GTK_OVERLAY_SCROLLING=0
export UV_SYSTEM_CERTS=true
unset NODE_EXTRA_CA_CERTS REQUESTS_CA_BUNDLE
mkdir -p "$HOME"
environment_script="$(dirname "${BASH_SOURCE[0]}")/../startup/environment-d.sh"
environment_file="$HOME/.config/environment.d/90-customshell.conf"
shell_file="$HOME/.config/customshell/env.sh"

expected_content=$'GTK_OVERLAY_SCROLLING=0\nUV_SYSTEM_CERTS=true'
expected_shell_content=$'# Generated by CustomShell; do not edit.\nexport GTK_OVERLAY_SCROLLING=\'0\'\nexport UV_SYSTEM_CERTS=\'true\''

source "$environment_script"
[[ "$(<"$environment_file")" == "$expected_content" ]] ||
	fail "environment.d content was not generated"
[[ "$(<"$shell_file")" == "$expected_shell_content" ]] ||
	fail "shell environment content was not generated"

original_environment_inode="$(stat -c %i "$environment_file")"
original_shell_inode="$(stat -c %i "$shell_file")"
source "$environment_script"
[[ "$(stat -c %i "$environment_file")" == "$original_environment_inode" ]] ||
	fail "unchanged environment.d content was republished"
[[ "$(stat -c %i "$shell_file")" == "$original_shell_inode" ]] ||
	fail "unchanged shell environment content was republished"

# mv
# Simulates a publication failure so preservation and cleanup can be asserted.
mv() { return 1; }
export GTK_OVERLAY_SCROLLING=1
source "$environment_script"
unset -f mv
[[ "$(<"$environment_file")" == "$expected_content" ]] ||
	fail "failed publication changed the existing environment.d file"
[[ "$(<"$shell_file")" == "$expected_shell_content" ]] ||
	fail "failed publication changed the existing shell environment file"
[[ -z "$(find "$(dirname "$environment_file")" -name '.90-customshell.conf.*' -print -quit)" ]] ||
	fail "failed publication left a temporary environment.d file"
[[ -z "$(find "$(dirname "$shell_file")" -name '.env.sh.*' -print -quit)" ]] ||
	fail "failed publication left a temporary shell environment file"

# Values with spaces, apostrophes, and shell metacharacters must survive the
# generated artifact exactly. The artifact is sourced by POSIX sh.
cert_dir="$test_root/certs"
mkdir -p "$cert_dir"
cert_file="$cert_dir/ca bundle's;test.pem"
printf 'test certificate\n' >"$cert_file"
export REQUESTS_CA_BUNDLE="$cert_file"
export NODE_EXTRA_CA_CERTS="$cert_file"
source "$environment_script"

rendered_values="$(
	env -i PATH=/usr/bin:/bin sh -c \
		'. "$1"; printf "%s\n%s\n" "$REQUESTS_CA_BUNDLE" "$NODE_EXTRA_CA_CERTS"' \
		sh "$shell_file"
)" || fail "shell environment file was not valid POSIX sh"
[[ "$rendered_values" == "$REQUESTS_CA_BUNDLE"$'\n'"$NODE_EXTRA_CA_CERTS" ]] ||
	fail "certificate values were not preserved by shell quoting"

# A certificate path that no longer exists is not published.
NODE_EXTRA_CA_CERTS="$test_root/missing.pem"
source "$environment_script"
grep -Fq 'NODE_EXTRA_CA_CERTS' "$shell_file" &&
	fail "missing certificate file was published to the shell environment"
grep -Fq 'NODE_EXTRA_CA_CERTS' "$environment_file" &&
	fail "missing certificate file was published to environment.d"

# The renderer handles every shell metacharacter, including $ and backticks,
# even though the environment.d publisher deliberately skips those values.
tricky='value with spaces and '\''quote'\'' $HOME `id`; * ? & | ( ) [ ] { } ! # ~ \ "'
rendered="$(customshell_render_shell_exports "CUSTOMSHELL_TRICKY=$tricky")"
tricky_actual="$(env -i PATH=/usr/bin:/bin sh -c "$rendered"'; printf "%s" "$CUSTOMSHELL_TRICKY"')" ||
	fail "shell renderer output was not valid POSIX sh"
[[ "$tricky_actual" == "$tricky" ]] ||
	fail "shell renderer changed a metacharacter value"

echo "Environment tests passed"
