#!/usr/bin/env bash
# shellcheck disable=SC2154

# Persistent user environment values managed by CustomShell setup. The managed
# shell block exports these values, and the runtime publishes them through
# environment.d for the systemd user session. This file only defines functions
# and is sourced by linux/install.sh.

# customshell_persistent_env_lines
# Prints the export statements added to the managed shell block.
customshell_persistent_env_lines() {
	printf 'export %s=%s\n' 'GTK_OVERLAY_SCROLLING' '0'
	printf 'export %s=%s\n' 'UV_SYSTEM_CERTS' 'true'
}

# customshell_environment_uninstall
# Removes the environment.d file and shell artifact generated by startup.
customshell_environment_uninstall() {
	local env_file="${HOME:?HOME is not set}/.config/environment.d/90-customshell.conf"
	local shell_file="${HOME:?HOME is not set}/.config/customshell/env.sh"

	if [[ -e "$env_file" || -L "$env_file" ]]; then
		if [[ "$dry_run" == true ]]; then
			say "Would remove $env_file"
		elif rm -f -- "$env_file"; then
			say "Removed $env_file"
		else
			return 1
		fi
	fi

	if [[ -e "$shell_file" || -L "$shell_file" ]]; then
		if [[ "$dry_run" == true ]]; then
			say "Would remove $shell_file"
		elif rm -f -- "$shell_file"; then
			say "Removed $shell_file"
		else
			return 1
		fi
	fi

	return 0
}

# customshell_environment_report
# Prints persistent environment state for the check report.
customshell_environment_report() {
	say "  GTK scroll: GTK_OVERLAY_SCROLLING=${GTK_OVERLAY_SCROLLING:-unset} (managed by the profile block)"
	say "  uv certs:   UV_SYSTEM_CERTS=${UV_SYSTEM_CERTS:-unset} (managed by the profile block)"
}
